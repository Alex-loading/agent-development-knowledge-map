const CREDIT = 'Agent Learner 原创教学图解';

function visual({
  id,
  kind = 'diagram',
  role,
  tags,
  title,
  alt,
  longDescription,
  caption,
  sourceIds,
  steps,
}) {
  const name = id.replace(/^visual-/, '');
  return {
    id,
    kind,
    role,
    tags,
    title,
    alt,
    longDescription,
    caption,
    assetPath: `assets/visuals/context-rag-memory/${name}.svg`,
    width: 1200,
    height: 675,
    provenance: 'original-synthesis',
    sourceIds,
    credit: CREDIT,
    permission: null,
    verifiedAt: VERIFIED_AT,
    fixtureId: `fixture-${name}`,
    ...(steps ? { steps } : {}),
  };
}

